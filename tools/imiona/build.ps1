#Requires -Version 5.1
<#
.SYNOPSIS
    Buduje plik danych imiona-data.js dla wyszukiwarki imion (imiona.html).

.DESCRIPTION
    Wejscie : data\imiona-2000-2019.csv  (kolumny: Rok,Imie,Liczba,Plec; UTF-8)
    Wyjscie : imiona-data.js             (window.IMIONA = { years, records, rows })

    Kazdy wiersz wynikowy to ["IMIE","M"|"K",[lata...]] gdzie tablica liczb ma
    dlugosc liczby lat, a 0 oznacza brak nadan w danym roku.

.PARAMETER Csv
    Sciezka do pliku CSV. Domyslnie data\imiona-2000-2019.csv obok tego skryptu.

.PARAMETER Out
    Sciezka do generowanego pliku JS. Domyslnie imiona-data.js obok tego skryptu.

.PARAMETER Download
    Pobiera CSV ze zrodla (dane.gov.pl / GUS) przed budowaniem.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\imiona\build.ps1

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\imiona\build.ps1 -Download
#>
[CmdletBinding()]
param(
    [string]$Csv,
    [string]$Out,
    [switch]$Download,
    [string]$Url = 'https://api.dane.gov.pl/media/resources/20200129/Imiona_nadane_wPolsce_w_latach_2000-2019.csv'
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

if (-not $Csv) { $Csv = Join-Path $PSScriptRoot 'data\imiona-2000-2019.csv' }
if (-not $Out) { $Out = Join-Path $PSScriptRoot 'imiona-data.js' }

$utf8 = New-Object System.Text.UTF8Encoding($false)

if ($Download) {
    $dir = Split-Path -Parent $Csv
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    Write-Host "Pobieram: $Url"
    $ProgressPreference = 'SilentlyContinue'
    Invoke-WebRequest -Uri $Url -OutFile $Csv -UseBasicParsing -TimeoutSec 120
}

if (-not (Test-Path -LiteralPath $Csv)) {
    throw "Brak pliku CSV: $Csv. Uruchom z parametrem -Download."
}

$lines = [System.IO.File]::ReadAllLines((Resolve-Path -LiteralPath $Csv).ProviderPath, $utf8)
Write-Host ("Wiersze w pliku: {0}" -f $lines.Count)

# --- naglowek: Rok,Imie,Liczba,Plec (kolejnosc sprawdzana po nazwach) ---
$header = $lines[0].Trim().Split(',')
if ($header.Count -ne 4 -or $header[0] -ne 'Rok') {
    throw ("Nieoczekiwany naglowek CSV: '{0}'. Oczekiwano: Rok,Imie,Liczba,Plec" -f $lines[0])
}

$years = New-Object 'System.Collections.Generic.List[int]'
$byKey = @{}          # "IMIE|M" -> int[] (indeks = pozycja roku)
$records = 0

for ($i = 1; $i -lt $lines.Count; $i++) {
    $line = $lines[$i]
    if ([string]::IsNullOrWhiteSpace($line)) { continue }

    $f = $line.Split(',')
    if ($f.Count -ne 4) { throw ("Linia {0}: oczekiwano 4 pol, jest {1}: '{2}'" -f ($i + 1), $f.Count, $line) }

    $year = 0
    $count = 0
    if (-not [int]::TryParse($f[0].Trim(), [ref]$year)) { throw ("Linia {0}: zly rok '{1}'" -f ($i + 1), $f[0]) }
    if (-not [int]::TryParse($f[2].Trim(), [ref]$count)) { throw ("Linia {0}: zla liczba '{1}'" -f ($i + 1), $f[2]) }

    $name = $f[1].Trim()
    $sex = $f[3].Trim()
    if ($name.Length -eq 0) { throw ("Linia {0}: puste imie" -f ($i + 1)) }
    if ($sex -ne 'M' -and $sex -ne 'K') { throw ("Linia {0}: nieznana plec '{1}'" -f ($i + 1), $sex) }

    if (-not $years.Contains($year)) { $years.Add($year) }
    $records++

    $key = "$name|$sex"
    if (-not $byKey.ContainsKey($key)) {
        $byKey[$key] = [ordered]@{ name = $name; sex = $sex; counts = @{} }
    }
    $slot = $byKey[$key].counts
    if ($slot.ContainsKey($year)) { throw ("Duplikat: {0} w roku {1}" -f $key, $year) }
    $slot[$year] = $count
}

$sortedYears = @($years | Sort-Object)
$yearIndex = @{}
for ($i = 0; $i -lt $sortedYears.Count; $i++) { $yearIndex[$sortedYears[$i]] = $i }
$nYears = $sortedYears.Count

$rows = New-Object 'System.Collections.Generic.List[object]'
foreach ($entry in $byKey.Values) {
    $counts = New-Object 'int[]' $nYears
    $total = 0
    foreach ($y in $entry.counts.Keys) {
        $counts[$yearIndex[$y]] = [int]$entry.counts[$y]
        $total += [int]$entry.counts[$y]
    }
    $rows.Add([pscustomobject]@{
        name   = $entry.name
        sex    = $entry.sex
        counts = $counts
        total  = $total
    })
}

# najpopularniejsze pierwsze: stabilna kolejnosc wyjscia (mniejszy diff przy przebudowie)
$rows.Sort([System.Comparison[object]] {
    param($a, $b)
    if ($a.total -ne $b.total) { return $b.total.CompareTo($a.total) }
    $c = [string]::CompareOrdinal($a.name, $b.name)
    if ($c -ne 0) { return $c }
    return [string]::CompareOrdinal($a.sex, $b.sex)
})

$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("/* AUTO-GENERATED by tools/imiona/build.ps1 from data/imiona-2000-2019.csv - do not edit by hand. */`n")
[void]$sb.Append("window.IMIONA={source:""https://dane.gov.pl/pl/dataset/219/resource/21458"",")
[void]$sb.Append("years:[$($sortedYears -join ',')],records:$records,rows:[`n")

$first = $true
foreach ($r in $rows) {
    if (-not $first) { [void]$sb.Append(",`n") }
    $first = $false
    $name = $r.name.Replace('\', '\\').Replace('"', '\"')
    [void]$sb.Append('["').Append($name).Append('","').Append($r.sex).Append('",[').Append(($r.counts -join ',')).Append(']]')
}
[void]$sb.Append("`n]};`n")

$outPath = [System.IO.Path]::GetFullPath($Out)
[System.IO.File]::WriteAllText($outPath, $sb.ToString(), $utf8)

$size = (Get-Item -LiteralPath $outPath).Length
Write-Host ("Zapisano: {0}" -f $outPath)
Write-Host ("Imion (imie+plec): {0} | rekordow: {1} | lat: {2} ({3}-{4}) | rozmiar: {5:N0} B" -f `
    $rows.Count, $records, $nYears, $sortedYears[0], $sortedYears[$nYears - 1], $size)
